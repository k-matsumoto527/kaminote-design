  var LANGS = { ja: 'ja', en: 'en', pt: 'pt-BR' };

  function mark(lang) {
    document.documentElement.setAttribute('lang', LANGS[lang] || 'ja');
    document.querySelectorAll('.lang button').forEach(function (b) {
      b.classList.toggle('on', b.getAttribute('data-lang') === lang);
      b.setAttribute('aria-pressed', b.getAttribute('data-lang') === lang ? 'true' : 'false');
    });
    try { localStorage.setItem('kaminote-lang', lang); } catch (e) {}
  }

  function apply(lang) {
    var d = DICT[lang];
    if (d) {
      document.querySelectorAll('[data-i18n]').forEach(function (el) {
        var t = d[el.getAttribute('data-i18n')];
        if (t !== undefined) { el.innerHTML = t; }
      });
    }
    mark(lang);
  }

  function boot() {
    var saved = null;
    try { saved = localStorage.getItem('kaminote-lang'); } catch (e) {}
    // 日本語のときは書き換えない（もとのHTMLがそのまま日本語なので、触るだけ無駄）
    if (saved && saved !== 'ja' && DICT[saved]) { apply(saved); } else { mark('ja'); }
    document.addEventListener('click', function (e) {
      var b = e.target && e.target.closest ? e.target.closest('.lang button') : null;
      if (b) { apply(b.getAttribute('data-lang')); }
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else { boot(); }
